const applyCustomAnswers = (vId: number, questions: Question[]): Question[] => {
  return questions.map((q) => {
    const customAns = getCustomAnswer(vId, q.question_number, q.correct_answer);
    if (customAns && customAns !== q.correct_answer) {
      return { ...q, correct_answer: customAns as any };
    }
    return q;
  });
};

export const getFallbackQuestions = (variantId: string | number): Question[] => {
  const vId = Number(variantId);

  const rawQuestions = getRawFallbackQuestions(vId);
  return applyCustomAnswers(vId, rawQuestions);
};

